package Atividade;

public class Pokemons {
	private int HP;
	private int ATK;
	private int DEF;
	private int SPD;
	private String Nome;
	private String Tipo;
	
	public String getNome() {
		return Nome;
	}
	public void setNome(String nome) {
		Nome = nome;
	}
	public String getTipo() {
		return Tipo;
	}
	public void setTipo(String tipo) {
		Tipo = tipo;
	}
	public int getHP() {
		return HP;
	}
	public void setHP(int hP) {
		HP = hP;
	}
	public int getATK() {
		return ATK;
	}
	public void setATK(int aTK) {
		ATK = aTK;
	}
	public int getDEF() {
		return DEF;
	}
	public void setDEF(int dEF) {
		DEF = dEF;
	}
	public int getSPD() {
		return SPD;
	}
	public void setSPD(int sPD) {
		SPD = sPD;
	}
	

}
